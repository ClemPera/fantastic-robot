# docker-compose.yml). all-minilm is ~46MB, light enough for a Pi; bump to
# ollama/nomic-embed-text (~274MB, better recall) if you have RAM to spare.
LETTA_EMBEDDING = os.environ.get("LETTA_EMBEDDING", "ollama/all-minilm")

